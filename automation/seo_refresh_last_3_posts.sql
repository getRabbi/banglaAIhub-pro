Sample project-এ before/after দেখান। শুধু final output নয়, process দেখান: brief, research, AI prompt, human edit, final deliverable।

## Client pitch template

Generic “I can do your work” message পাঠাবেন না। Client-এর specific problem ধরুন।

Pitch structure:

1. তাদের business বা post সম্পর্কে ১ line observation
2. কোন সমস্যা দেখলেন তা বলুন
3. আপনার package কীভাবে solve করবে
4. ১টি sample বা demo link দিন
5. ছোট next step দিন

Example:

“আপনার product page-গুলোতে description আছে, কিন্তু FAQ এবং comparison angle নেই। আমি ৫টি product-এর জন্য SEO-friendly description, ad hook এবং FAQ বানিয়ে দিতে পারি। চাইলে ১টি sample আগে পাঠাতে পারি।”

## Quality assurance

AI output client-কে raw পাঠাবেন না। Delivery-এর আগে check করুন:

- client brief follow করা হয়েছে কি?
- repeated phrase বাদ গেছে কি?
- fact, price, tool name verify করা হয়েছে কি?
- grammar ও tone consistent কি?
- deliverable file clean format-এ আছে কি?
- CTA বা next action clear কি?

## Communication rule

Freelancing-এ quality যত জরুরি, communication তত জরুরি। Client update না পেলে trust কমে যায়।

- order নেওয়ার পর scope recap পাঠান
- midway update দিন
- delay হলে আগে জানান
- revision request লিখিতভাবে confirm করুন
- final delivery-তে কী included আছে list দিন

## FAQ

### AI দিয়ে freelancing করলে client আপত্তি করবে?

সাধারণত না, যদি আপনি honest থাকেন এবং final quality ভালো হয়। Client raw AI text না, polished result কিনে।

### কোন marketplace দিয়ে শুরু করব?

Fiverr, Upwork, LinkedIn এবং local Facebook business group ব্যবহার করতে পারেন। তবে platform যাই হোক, package এবং sample পরিষ্কার থাকা জরুরি।

### একসাথে কত service offer করা উচিত?

শুরুতে ১-২টি service যথেষ্ট। অনেক service দিলে positioning weak হয় এবং portfolio focus থাকে না।

### Revision policy কীভাবে লিখব?

প্রতিটি package-এ কত revision included এবং revision কী ধরনের change cover করবে তা লিখুন। New scope হলে extra charge নিন।

### AI tool cost client-এর কাছ থেকে নেব?

যদি paid API/tool project-এর জন্য লাগে, quote-এ আলাদা করে tool cost mention করুন। Hidden cost রাখবেন না।

### First client না পেলে কী করব?

Sample improve করুন, pitch specific করুন, ২০-৩০টি targeted outreach করুন এবং small starter package offer করুন। Random broad post-এর চেয়ে targeted outreach বেশি কার্যকর।

