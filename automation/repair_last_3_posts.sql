## AI content workflow কেমন হবে

একটি ভালো workflow সাধারণত ৬ ধাপে চলে:

1. **Research:** audience কোন প্রশ্ন করছে, competitor কী লিখছে, Google/YouTube/Facebook-এ কী search হচ্ছে দেখুন।
2. **Outline:** AI দিয়ে outline নিন, কিন্তু blind copy করবেন না। local example এবং নিজের judgment যোগ করুন।
3. **Draft:** blog, carousel, script বা newsletter draft বানান।
4. **Human edit:** claim, pricing, tool feature, spelling, tone এবং readability check করুন।
5. **Publish:** blog বা social platform-এ post করুন।
6. **Repurpose:** একই content থেকে short video script, Facebook post, LinkedIn post, infographic point বানান।

এখানে AI আপনার assistant, editor না। শেষ decision human review ছাড়া publish করা উচিত না।

