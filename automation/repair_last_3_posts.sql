## Pricing কীভাবে ভাববেন

শুরুতে pricing কম রাখতেই হবে এমন নয়। কিন্তু price justify করার মতো deliverable থাকতে হবে।

Pricing model:

- Basic: small deliverable, fast delivery
- Standard: full package
- Premium: strategy + delivery + revision + repurpose

Example:

| Tier | Deliverable | Best for |
|---|---|---|
| Basic | ৫ idea + ২ draft | trial client |
| Standard | ১০ idea + ৪ draft + captions | regular content |
| Premium | strategy + ৮ draft + calendar | serious business |

Price দেওয়ার আগে কাজের complexity, research time, editing time এবং revision load হিসাব করুন।

