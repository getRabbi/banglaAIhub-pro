## Common mistake

সবচেয়ে বড় ভুল হলো raw AI output client-কে দেওয়া। এতে repeat client পাওয়া কঠিন। আরেকটি ভুল হলো requirement না নিয়ে কাজ শুরু করা। Client brief পরিষ্কার না হলে output mismatch হবেই।

প্রতিটি project-এ brief, outline approval, draft, revision এবং final handover flow রাখুন।

